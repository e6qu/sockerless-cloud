package main

import (
	"fmt"
	"net/http"
	"strings"

	"github.com/e6qu/sockerless-cloud/sim"
)

type PrivateDnsZone struct {
	ID         string            `json:"id"`
	Name       string            `json:"name"`
	Type       string            `json:"type"`
	Location   string            `json:"location"`
	Etag       string            `json:"etag,omitempty"`
	Tags       map[string]string `json:"tags,omitempty"`
	Properties DnsZoneProperties `json:"properties"`
}

type DnsZoneProperties struct {
	MaxNumberOfRecordSets                 int    `json:"maxNumberOfRecordSets"`
	NumberOfRecordSets                    int    `json:"numberOfRecordSets"`
	MaxNumberOfVirtualNetworkLinks        int    `json:"maxNumberOfVirtualNetworkLinks"`
	NumberOfVirtualNetworkLinks           int    `json:"numberOfVirtualNetworkLinks"`
	MaxNumberOfVirtualNetworkLinksWithReg int    `json:"maxNumberOfVirtualNetworkLinksWithRegistration"`
	NumberOfVirtualNetworkLinksWithReg    int    `json:"numberOfVirtualNetworkLinksWithRegistration"`
	ProvisioningState                     string `json:"provisioningState"`
}

type RecordSet struct {
	ID         string              `json:"id"`
	Name       string              `json:"name"`
	Type       string              `json:"type"`
	Etag       string              `json:"etag,omitempty"`
	Properties RecordSetProperties `json:"properties"`
}

// Azure Private DNS serves A, AAAA, CNAME, MX, PTR, SOA, SRV and TXT record
// sets.
type RecordSetProperties struct {
	TTL              int               `json:"ttl,omitempty"`
	Fqdn             string            `json:"fqdn,omitempty"`
	IsAutoRegistered bool              `json:"isAutoRegistered"`
	ARecords         []ARecord         `json:"aRecords,omitempty"`
	AAAARecords      []AAAARecord      `json:"aaaaRecords,omitempty"`
	CNAMERecord      *CNAMERecord      `json:"cnameRecord,omitempty"`
	MXRecords        []MXRecord        `json:"mxRecords,omitempty"`
	PTRRecords       []PTRRecord       `json:"ptrRecords,omitempty"`
	SRVRecords       []SRVRecord       `json:"srvRecords,omitempty"`
	TXTRecords       []TXTRecord       `json:"txtRecords,omitempty"`
	SOARecord        *SOARecord        `json:"soaRecord,omitempty"`
	Metadata         map[string]string `json:"metadata,omitempty"`
}

type ARecord struct {
	IPv4Address string `json:"ipv4Address"`
}

type AAAARecord struct {
	IPv6Address string `json:"ipv6Address"`
}

// A name has at most one CNAME, so this is a singleton.
type CNAMERecord struct {
	CName string `json:"cname"`
}

type MXRecord struct {
	Preference int32  `json:"preference"`
	Exchange   string `json:"exchange"`
}

type PTRRecord struct {
	PTRDName string `json:"ptrdname"`
}

type SRVRecord struct {
	Priority int32  `json:"priority"`
	Weight   int32  `json:"weight"`
	Port     int32  `json:"port"`
	Target   string `json:"target"`
}

// Azure splits long TXT values into chunks of at most 255 bytes.
type TXTRecord struct {
	Value []string `json:"value"`
}

// SOARecord is autogenerated for new zones.
type SOARecord struct {
	Host         string `json:"host,omitempty"`
	Email        string `json:"email,omitempty"`
	SerialNumber int64  `json:"serialNumber,omitempty"`
	RefreshTime  int32  `json:"refreshTime,omitempty"`
	RetryTime    int32  `json:"retryTime,omitempty"`
	ExpireTime   int32  `json:"expireTime,omitempty"`
	MinimumTTL   int32  `json:"minimumTtl,omitempty"`
}

type VNetLink struct {
	ID         string             `json:"id"`
	Name       string             `json:"name"`
	Type       string             `json:"type"`
	Location   string             `json:"location"`
	Tags       map[string]string  `json:"tags,omitempty"`
	Properties VNetLinkProperties `json:"properties"`
}

type VNetLinkProperties struct {
	VirtualNetwork          *VNetLinkVNet `json:"virtualNetwork,omitempty"`
	RegistrationEnabled     bool          `json:"registrationEnabled"`
	VirtualNetworkLinkState string        `json:"virtualNetworkLinkState"`
	ProvisioningState       string        `json:"provisioningState"`
}

type VNetLinkVNet struct {
	ID string `json:"id"`
}

var (
	azurePrivateDNSZones      sim.Store[PrivateDnsZone]
	azurePrivateDNSRecordSets sim.Store[RecordSet]
	azurePrivateDNSVNetLinks  sim.Store[VNetLink]
)

func registerPrivateDNS(srv *sim.Server) {
	zones := sim.MakeStore[PrivateDnsZone](srv.DB(), "dns_zones")
	recordSets := sim.MakeStore[RecordSet](srv.DB(), "dns_record_sets")
	azurePrivateDNSZones = zones
	azurePrivateDNSRecordSets = recordSets

	const armBase = "/subscriptions/{subscriptionId}/resourceGroups/{resourceGroupName}/providers/Microsoft.Network"

	srv.HandleFunc("PUT "+armBase+"/privateDnsZones/{zoneName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")

		var req PrivateDnsZone
		if err := sim.ReadJSON(r, &req); err != nil {
			AzureError(w, "InvalidRequestContent", "Failed to parse request body: "+err.Error(), http.StatusBadRequest)
			return
		}

		location := req.Location
		if location == "" {
			location = "global"
		}

		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)

		_, exists := zones.Get(resourceID)

		zone := PrivateDnsZone{
			ID:       resourceID,
			Name:     zoneName,
			Type:     "Microsoft.Network/privateDnsZones",
			Location: strings.ToLower(location),
			Etag:     sim.NewUUID(),
			Tags:     req.Tags,
			Properties: DnsZoneProperties{
				MaxNumberOfRecordSets:                 25000,
				NumberOfRecordSets:                    0,
				MaxNumberOfVirtualNetworkLinks:        1000,
				NumberOfVirtualNetworkLinks:           0,
				MaxNumberOfVirtualNetworkLinksWithReg: 100,
				NumberOfVirtualNetworkLinksWithReg:    0,
				ProvisioningState:                     "Succeeded",
			},
		}

		records := recordSets.Filter(func(rs RecordSet) bool {
			return strings.HasPrefix(rs.ID, resourceID+"/")
		})
		zone.Properties.NumberOfRecordSets = len(records)

		zones.Put(resourceID, zone)

		// The azurerm provider reads the SOA record after zone creation.
		if !exists {
			soaID := fmt.Sprintf("%s/SOA/@", resourceID)
			if _, soaExists := recordSets.Get(soaID); !soaExists {
				recordSets.Put(soaID, RecordSet{
					ID:   soaID,
					Name: "@",
					Type: "Microsoft.Network/privateDnsZones/SOA",
					Etag: sim.NewUUID(),
					Properties: RecordSetProperties{
						TTL:  3600,
						Fqdn: zoneName + ".",
						SOARecord: &SOARecord{
							Host:         "azureprivatedns.net",
							Email:        "azureprivatedns-host.microsoft.com",
							SerialNumber: 1,
							RefreshTime:  3600,
							RetryTime:    300,
							ExpireTime:   2419200,
							MinimumTTL:   300,
						},
					},
				})
				zone.Properties.NumberOfRecordSets = 1
				zones.Put(resourceID, zone)
			}
		}

		// go-azure-sdk expects 200 for a synchronous create.
		sim.WriteJSON(w, http.StatusOK, zone)
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		prefix := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones") + "/"
		all := zones.Filter(func(z PrivateDnsZone) bool {
			return strings.HasPrefix(z.ID, prefix)
		})
		page, next, pageOK := armPage(w, r, all, func(z PrivateDnsZone) string { return z.Name })
		if !pageOK {
			return
		}
		out := map[string]any{"value": page}
		if next != "" {
			out["nextLink"] = armNextLink(r, next)
		}
		sim.WriteJSON(w, http.StatusOK, out)
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")

		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)

		zone, ok := zones.Get(resourceID)
		if !ok {
			AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
				"The Resource 'Microsoft.Network/privateDnsZones/%s' under resource group '%s' was not found.", zoneName, rg)
			return
		}

		sim.WriteJSON(w, http.StatusOK, zone)
	})

	srv.HandleFunc("DELETE "+armBase+"/privateDnsZones/{zoneName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")

		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)

		if zones.Delete(resourceID) {
			records := recordSets.Filter(func(rs RecordSet) bool {
				return strings.HasPrefix(rs.ID, resourceID+"/")
			})
			for _, rs := range records {
				recordSets.Delete(rs.ID)
			}
			w.WriteHeader(http.StatusOK)
		} else {
			w.WriteHeader(http.StatusNoContent)
		}
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}/SOA/{recordName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		recordName := sim.PathParam(r, "recordName")

		recordID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "SOA", recordName)

		rs, ok := recordSets.Get(recordID)
		if !ok {
			AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
				"The record set '%s' of type 'SOA' in zone '%s' was not found.", recordName, zoneName)
			return
		}

		sim.WriteJSON(w, http.StatusOK, rs)
	})

	srv.HandleFunc("PUT "+armBase+"/privateDnsZones/{zoneName}/A/{recordName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		recordName := sim.PathParam(r, "recordName")

		zoneID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)
		if _, ok := zones.Get(zoneID); !ok {
			AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
				"The Resource 'Microsoft.Network/privateDnsZones/%s' under resource group '%s' was not found.", zoneName, rg)
			return
		}

		var req RecordSet
		if err := sim.ReadJSON(r, &req); err != nil {
			AzureError(w, "InvalidRequestContent", "Failed to parse request body: "+err.Error(), http.StatusBadRequest)
			return
		}

		recordID := fmt.Sprintf("%s/A/%s", zoneID, recordName)

		ttl := req.Properties.TTL
		if ttl == 0 {
			ttl = 3600
		}

		rs := RecordSet{
			ID:   recordID,
			Name: recordName,
			Type: "Microsoft.Network/privateDnsZones/A",
			Etag: sim.NewUUID(),
			Properties: RecordSetProperties{
				TTL:              ttl,
				Fqdn:             recordName + "." + zoneName + ".",
				IsAutoRegistered: false,
				ARecords:         req.Properties.ARecords,
				Metadata:         req.Properties.Metadata,
			},
		}

		recordSets.Put(recordID, rs)

		zones.Update(zoneID, func(z *PrivateDnsZone) {
			records := recordSets.Filter(func(r RecordSet) bool {
				return strings.HasPrefix(r.ID, zoneID+"/")
			})
			z.Properties.NumberOfRecordSets = len(records)
		})

		// go-azure-sdk expects 200 for a synchronous create.
		sim.WriteJSON(w, http.StatusOK, rs)
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}/A/{recordName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		recordName := sim.PathParam(r, "recordName")

		recordID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "A", recordName)

		rs, ok := recordSets.Get(recordID)
		if !ok {
			AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
				"The record set '%s' of type 'A' in zone '%s' was not found.", recordName, zoneName)
			return
		}

		sim.WriteJSON(w, http.StatusOK, rs)
	})

	srv.HandleFunc("DELETE "+armBase+"/privateDnsZones/{zoneName}/A/{recordName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		recordName := sim.PathParam(r, "recordName")

		zoneID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)
		recordID := fmt.Sprintf("%s/A/%s", zoneID, recordName)

		if recordSets.Delete(recordID) {
			zones.Update(zoneID, func(z *PrivateDnsZone) {
				records := recordSets.Filter(func(r RecordSet) bool {
					return strings.HasPrefix(r.ID, zoneID+"/")
				})
				z.Properties.NumberOfRecordSets = len(records)
			})
			w.WriteHeader(http.StatusOK)
		} else {
			w.WriteHeader(http.StatusNoContent)
		}
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}/A", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")

		prefix := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "A") + "/"

		filtered := recordSets.Filter(func(rs RecordSet) bool {
			return strings.HasPrefix(rs.ID, prefix)
		})

		sim.WriteJSON(w, http.StatusOK, map[string]any{
			"value": filtered,
		})
	})

	// The other record types share one CRUD shape; the path's `recordType` segment
	// selects the field of RecordSetProperties that holds the records.
	for _, rt := range []string{"AAAA", "CNAME", "MX", "PTR", "SRV", "TXT"} {
		recordType := rt
		srv.HandleFunc(
			"PUT "+armBase+"/privateDnsZones/{zoneName}/"+recordType+"/{recordName}",
			func(w http.ResponseWriter, r *http.Request) {
				sub := sim.PathParam(r, "subscriptionId")
				rg := sim.PathParam(r, "resourceGroupName")
				zoneName := sim.PathParam(r, "zoneName")
				recordName := sim.PathParam(r, "recordName")
				zoneID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)
				if _, ok := zones.Get(zoneID); !ok {
					AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
						"Zone %q not found in resource group %q", zoneName, rg)
					return
				}
				var req RecordSet
				if err := sim.ReadJSON(r, &req); err != nil {
					AzureError(w, "InvalidRequestContent",
						"Failed to parse request body: "+err.Error(), http.StatusBadRequest)
					return
				}
				ttl := req.Properties.TTL
				if ttl == 0 {
					ttl = 3600
				}
				recordID := fmt.Sprintf("%s/%s/%s", zoneID, recordType, recordName)
				rs := RecordSet{
					ID:   recordID,
					Name: recordName,
					Type: "Microsoft.Network/privateDnsZones/" + recordType,
					Etag: sim.NewUUID(),
					Properties: RecordSetProperties{
						TTL:              ttl,
						Fqdn:             recordName + "." + zoneName + ".",
						IsAutoRegistered: false,
						AAAARecords:      req.Properties.AAAARecords,
						CNAMERecord:      req.Properties.CNAMERecord,
						MXRecords:        req.Properties.MXRecords,
						PTRRecords:       req.Properties.PTRRecords,
						SRVRecords:       req.Properties.SRVRecords,
						TXTRecords:       req.Properties.TXTRecords,
						Metadata:         req.Properties.Metadata,
					},
				}
				recordSets.Put(recordID, rs)
				zones.Update(zoneID, func(z *PrivateDnsZone) {
					records := recordSets.Filter(func(r RecordSet) bool {
						return strings.HasPrefix(r.ID, zoneID+"/")
					})
					z.Properties.NumberOfRecordSets = len(records)
				})
				sim.WriteJSON(w, http.StatusOK, rs)
			})

		srv.HandleFunc(
			"GET "+armBase+"/privateDnsZones/{zoneName}/"+recordType+"/{recordName}",
			func(w http.ResponseWriter, r *http.Request) {
				sub := sim.PathParam(r, "subscriptionId")
				rg := sim.PathParam(r, "resourceGroupName")
				zoneName := sim.PathParam(r, "zoneName")
				recordName := sim.PathParam(r, "recordName")
				recordID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, recordType, recordName)
				rs, ok := recordSets.Get(recordID)
				if !ok {
					AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
						"The record set '%s' of type '%s' in zone '%s' was not found.",
						recordName, recordType, zoneName)
					return
				}
				sim.WriteJSON(w, http.StatusOK, rs)
			})

		srv.HandleFunc(
			"DELETE "+armBase+"/privateDnsZones/{zoneName}/"+recordType+"/{recordName}",
			func(w http.ResponseWriter, r *http.Request) {
				sub := sim.PathParam(r, "subscriptionId")
				rg := sim.PathParam(r, "resourceGroupName")
				zoneName := sim.PathParam(r, "zoneName")
				recordName := sim.PathParam(r, "recordName")
				zoneID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName)
				recordID := fmt.Sprintf("%s/%s/%s", zoneID, recordType, recordName)
				if recordSets.Delete(recordID) {
					zones.Update(zoneID, func(z *PrivateDnsZone) {
						records := recordSets.Filter(func(r RecordSet) bool {
							return strings.HasPrefix(r.ID, zoneID+"/")
						})
						z.Properties.NumberOfRecordSets = len(records)
					})
					w.WriteHeader(http.StatusOK)
				} else {
					w.WriteHeader(http.StatusNoContent)
				}
			})

		srv.HandleFunc(
			"GET "+armBase+"/privateDnsZones/{zoneName}/"+recordType,
			func(w http.ResponseWriter, r *http.Request) {
				sub := sim.PathParam(r, "subscriptionId")
				rg := sim.PathParam(r, "resourceGroupName")
				zoneName := sim.PathParam(r, "zoneName")
				prefix := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, recordType) + "/"
				filtered := recordSets.Filter(func(rs RecordSet) bool {
					return strings.HasPrefix(rs.ID, prefix)
				})
				sim.WriteJSON(w, http.StatusOK, map[string]any{"value": filtered})
			})
	}

	vnetLinks := sim.MakeStore[VNetLink](srv.DB(), "dns_vnet_links")
	azurePrivateDNSVNetLinks = vnetLinks

	srv.HandleFunc("PUT "+armBase+"/privateDnsZones/{zoneName}/virtualNetworkLinks/{linkName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		linkName := sim.PathParam(r, "linkName")

		var req VNetLink
		if err := sim.ReadJSON(r, &req); err != nil {
			AzureError(w, "InvalidRequestContent", "Failed to parse request body", http.StatusBadRequest)
			return
		}

		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "virtualNetworkLinks", linkName)

		link := VNetLink{
			ID:       resourceID,
			Name:     linkName,
			Type:     "Microsoft.Network/privateDnsZones/virtualNetworkLinks",
			Location: "global",
			Tags:     req.Tags,
			Properties: VNetLinkProperties{
				VirtualNetwork:          req.Properties.VirtualNetwork,
				RegistrationEnabled:     req.Properties.RegistrationEnabled,
				VirtualNetworkLinkState: "Completed",
				ProvisioningState:       "Succeeded",
			},
		}
		vnetLinks.Put(resourceID, link)
		azureReconcileAutoRegisteredRecords()

		// go-azure-sdk expects 200 for a synchronous create.
		sim.WriteJSON(w, http.StatusOK, link)
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}/virtualNetworkLinks", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		prefix := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "virtualNetworkLinks") + "/"
		filtered := vnetLinks.Filter(func(link VNetLink) bool {
			return strings.HasPrefix(link.ID, prefix)
		})
		sim.WriteJSON(w, http.StatusOK, map[string]any{"value": filtered})
	})

	srv.HandleFunc("GET "+armBase+"/privateDnsZones/{zoneName}/virtualNetworkLinks/{linkName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		linkName := sim.PathParam(r, "linkName")
		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "virtualNetworkLinks", linkName)

		link, ok := vnetLinks.Get(resourceID)
		if !ok {
			AzureErrorf(w, "ResourceNotFound", http.StatusNotFound,
				"Virtual network link '%s' not found.", linkName)
			return
		}
		sim.WriteJSON(w, http.StatusOK, link)
	})

	srv.HandleFunc("DELETE "+armBase+"/privateDnsZones/{zoneName}/virtualNetworkLinks/{linkName}", func(w http.ResponseWriter, r *http.Request) {
		sub := sim.PathParam(r, "subscriptionId")
		rg := sim.PathParam(r, "resourceGroupName")
		zoneName := sim.PathParam(r, "zoneName")
		linkName := sim.PathParam(r, "linkName")
		resourceID := armResourceID(sub, rg, "Microsoft.Network", "privateDnsZones", zoneName, "virtualNetworkLinks", linkName)

		vnetLinks.Delete(resourceID)
		azureReconcileAutoRegisteredRecords()
		w.WriteHeader(http.StatusAccepted)
	})

	registerPrivateDNSMore(srv, zones, recordSets, vnetLinks)
}
