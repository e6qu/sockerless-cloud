//go:build ignore

// gen-cloudwatch-logs-ocsf writes simulator-aws/cloudwatch_logs_transformer_ocsf_gen.go
// from the vendored OCSF 1.1.0 and 1.5.0 schemas and the Amazon Security Lake
// mapping dossiers in ocsf/examples, which the parseToOCSF processor follows.
//
// Run from the repository root (scripts/fetch-cloudwatch-logs-transformer-sources.sh
// runs it after vendoring):
//
//	go run scripts/gen-cloudwatch-logs-ocsf.go
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const specDir = "specs/cloud-api/aws/"

var versions = []string{"1.1.0", "1.5.0"}

// The dossier directories of each version, by the class they map to.
var dossierDirs = []struct{ source, dir string }{
	{"CloudTrail", "CloudTrail/API Activity"},
	{"CloudTrail", "CloudTrail/Account Change"},
	{"CloudTrail", "CloudTrail/Authentication"},
	{"Route53Resolver", "Route53"},
	{"VPCFlow", "VPC Flowlogs"},
	{"EKSAudit", "EKS Audit Logs"},
	{"AWSWAF", "WAF"},
}

func main() {
	var out bytes.Buffer
	out.WriteString("// Code generated by scripts/gen-cloudwatch-logs-ocsf.go from specs/cloud-api/aws/ocsf-*. DO NOT EDIT.\n\npackage main\n\n")
	out.WriteString("var cwoSchemas = map[string]*cwoSchema{\n")
	for _, v := range versions {
		writeSchema(&out, v)
	}
	out.WriteString("}\n\n")
	out.WriteString("var cwoDossiers = []cwoDossier{\n")
	for _, v := range versions {
		writeDossiers(&out, v)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("simulator-aws/cloudwatch_logs_transformer_ocsf_gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func readGz(name string) []byte {
	f, err := os.Open(specDir + name)
	if err != nil {
		fail(err)
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		fail(err)
	}
	b, err := io.ReadAll(zr)
	if err != nil {
		fail(err)
	}
	return b
}

func readTar(name string) map[string][]byte {
	zr, err := gzip.NewReader(bytes.NewReader(mustReadFile(specDir + name)))
	if err != nil {
		fail(err)
	}
	files := map[string][]byte{}
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return files
		}
		if err != nil {
			fail(err)
		}
		if h.Typeflag != tar.TypeReg {
			continue
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			fail(err)
		}
		files[h.Name] = b
	}
}

func mustReadFile(p string) []byte {
	b, err := os.ReadFile(p)
	if err != nil {
		fail(err)
	}
	return b
}

type enumDef map[string]struct {
	Caption string `json:"caption"`
}

type attrDef struct {
	Type    string  `json:"type"`
	IsArray bool    `json:"is_array"`
	Enum    enumDef `json:"enum"`
}

type typeDef struct {
	Caption    string `json:"caption"`
	Type       string `json:"type"`
	Observable int    `json:"observable"`
}

type schemaFile struct {
	Name       string                     `json:"name"`
	Caption    string                     `json:"caption"`
	Extends    string                     `json:"extends"`
	Category   string                     `json:"category"`
	UID        *int                       `json:"uid"`
	Attributes map[string]json.RawMessage `json:"attributes"`
}

func decodeAttrs(raw map[string]json.RawMessage) map[string]attrDef {
	out := map[string]attrDef{}
	for k, v := range raw {
		if strings.HasPrefix(k, "$") {
			continue
		}
		var a attrDef
		if err := json.Unmarshal(v, &a); err != nil {
			fail(fmt.Errorf("attribute %s: %v", k, err))
		}
		out[k] = a
	}
	return out
}

func mergeAttr(base, over attrDef) attrDef {
	if over.Type != "" {
		base.Type = over.Type
	}
	base.IsArray = base.IsArray || over.IsArray
	if len(over.Enum) > 0 {
		merged := enumDef{}
		for k, v := range base.Enum {
			merged[k] = v
		}
		for k, v := range over.Enum {
			merged[k] = v
		}
		base.Enum = merged
	}
	return base
}

func enumMap(e enumDef) map[int]string {
	m := map[int]string{}
	for k, v := range e {
		n, err := strconv.Atoi(k)
		if err != nil {
			continue
		}
		m[n] = v.Caption
	}
	return m
}

func writeEnum(out *bytes.Buffer, key string, m map[int]string) {
	ids := make([]int, 0, len(m))
	for id := range m {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	fmt.Fprintf(out, "%q: {", key)
	for _, id := range ids {
		fmt.Fprintf(out, "%d: %q, ", id, m[id])
	}
	out.WriteString("},\n")
}

// chain resolves a definition's extends chain, root first.
func chain(defs map[string]schemaFile, name string) []schemaFile {
	var c []schemaFile
	for name != "" {
		d, ok := defs[name]
		if !ok {
			break
		}
		c = append([]schemaFile{d}, c...)
		name = d.Extends
	}
	return c
}

func writeSchema(out *bytes.Buffer, v string) {
	var dict struct {
		Attributes map[string]json.RawMessage `json:"attributes"`
		Types      struct {
			Attributes map[string]typeDef `json:"attributes"`
		} `json:"types"`
	}
	if err := json.Unmarshal(readGz("ocsf-schema-v"+v+"-dictionary.json.gz"), &dict); err != nil {
		fail(err)
	}
	var cats struct {
		Attributes map[string]struct {
			Caption string `json:"caption"`
			UID     int    `json:"uid"`
		} `json:"attributes"`
	}
	if err := json.Unmarshal(readGz("ocsf-schema-v"+v+"-categories.json.gz"), &cats); err != nil {
		fail(err)
	}
	load := func(name string) map[string]schemaFile {
		defs := map[string]schemaFile{}
		for p, b := range readTar(name) {
			if !strings.HasSuffix(p, ".json") {
				continue
			}
			var d schemaFile
			if err := json.Unmarshal(b, &d); err != nil {
				fail(fmt.Errorf("%s: %v", p, err))
			}
			if d.Name == "" {
				continue
			}
			if d.Category == "" && strings.HasPrefix(p, "events/") {
				if parts := strings.Split(p, "/"); len(parts) == 3 {
					d.Category = parts[1]
				}
			}
			defs[d.Name] = d
		}
		return defs
	}
	events := load("ocsf-schema-v" + v + "-events.tar.gz")
	objects := load("ocsf-schema-v" + v + "-objects.tar.gz")
	includes := map[string]map[string]json.RawMessage{}
	for _, part := range []string{"profiles", "includes"} {
		if _, err := os.Stat(specDir + "ocsf-schema-v" + v + "-" + part + ".tar.gz"); err != nil {
			continue
		}
		for p, b := range readTar("ocsf-schema-v" + v + "-" + part + ".tar.gz") {
			var d schemaFile
			if err := json.Unmarshal(b, &d); err != nil {
				fail(fmt.Errorf("%s: %v", p, err))
			}
			includes[p] = d.Attributes
		}
	}
	// withIncludes merges the attributes a definition's $include names under
	// its own.
	var withIncludes func(raw map[string]json.RawMessage) map[string]attrDef
	withIncludes = func(raw map[string]json.RawMessage) map[string]attrDef {
		out := map[string]attrDef{}
		if inc, ok := raw["$include"]; ok {
			var paths []string
			if err := json.Unmarshal(inc, &paths); err != nil {
				var one string
				if err := json.Unmarshal(inc, &one); err != nil {
					fail(fmt.Errorf("$include %s: %v", inc, err))
				}
				paths = []string{one}
			}
			for _, p := range paths {
				attrs, ok := includes[p]
				if !ok {
					fail(fmt.Errorf("$include %s is not vendored", p))
				}
				for k, a := range withIncludes(attrs) {
					out[k] = mergeAttr(out[k], a)
				}
			}
		}
		for k, a := range decodeAttrs(raw) {
			out[k] = mergeAttr(out[k], a)
		}
		return out
	}
	attrs := decodeAttrs(dict.Attributes)

	fmt.Fprintf(out, "%q: {\nversion: %q,\n", v, v)
	out.WriteString("types: map[string]cwoType{\n")
	for _, name := range sortedKeys(dict.Types.Attributes) {
		t := dict.Types.Attributes[name]
		fmt.Fprintf(out, "%q: {base: %q, caption: %q, observable: %d},\n", name, t.Type, t.Caption, t.Observable)
	}
	out.WriteString("},\nattrs: map[string]cwoAttr{\n")
	for _, name := range sortedKeys(attrs) {
		a := attrs[name]
		fmt.Fprintf(out, "%q: {typ: %q, array: %v},\n", name, a.Type, a.IsArray)
	}
	out.WriteString("},\nenums: map[string]map[int]string{\n")
	for _, name := range sortedKeys(attrs) {
		if len(attrs[name].Enum) > 0 {
			writeEnum(out, name, enumMap(attrs[name].Enum))
		}
	}
	scoped := func(defs map[string]schemaFile) (map[string]map[int]string, map[string]string) {
		enums, types := map[string]map[int]string{}, map[string]string{}
		for _, name := range sortedKeys(defs) {
			if strings.HasPrefix(name, "_") {
				continue
			}
			merged := map[string]map[int]string{}
			for _, d := range chain(defs, name) {
				for an, a := range withIncludes(d.Attributes) {
					if len(a.Enum) > 0 {
						if merged[an] == nil {
							merged[an] = map[int]string{}
						}
						for id, c := range enumMap(a.Enum) {
							merged[an][id] = c
						}
					}
					if a.Type != "" {
						types[name+"."+an] = a.Type
					}
				}
			}
			for an, m := range merged {
				enums[name+"."+an] = m
			}
		}
		return enums, types
	}
	eventEnums, eventTypes := scoped(events)
	objectEnums, objectTypes := scoped(objects)
	for _, src := range []map[string]map[int]string{eventEnums, objectEnums} {
		for _, k := range sortedKeys(src) {
			writeEnum(out, k, src[k])
		}
	}
	out.WriteString("},\nscopedTypes: map[string]string{\n")
	for _, src := range []map[string]string{eventTypes, objectTypes} {
		for _, k := range sortedKeys(src) {
			fmt.Fprintf(out, "%q: %q,\n", k, src[k])
		}
	}
	out.WriteString("},\nclasses: map[string]cwoClass{\n")
	for _, name := range sortedKeys(events) {
		e := events[name]
		cat, ok := cats.Attributes[e.Category]
		if e.UID == nil || !ok {
			continue
		}
		fmt.Fprintf(out, "%q: {uid: %d, caption: %q, categoryUID: %d, categoryCaption: %q},\n",
			name, cat.UID*1000+*e.UID, e.Caption, cat.UID, cat.Caption)
	}
	out.WriteString("},\n},\n")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

var (
	bulletRE = regexp.MustCompile("^\\s*-\\s*`([^`]+)`:\\s*`(.*)`\\s*$")
	cellRE   = regexp.MustCompile("`([^`]*)`")
)

// dossier parses a mapping dossier: the OCSF Version list of constant
// attributes, the Mapping table and the Conditional Mapping table.
func writeDossiers(out *bytes.Buffer, v string) {
	files := readTar("ocsf-examples-aws-v" + v + ".tar.gz")
	base := "mappings/markdown/AWS/v" + v + "/"
	for _, d := range dossierDirs {
		readme, ok := files[base+d.dir+"/README.md"]
		if !ok {
			fail(fmt.Errorf("%s%s/README.md is not vendored", base, d.dir))
		}
		section := ""
		reversed := false
		var consts, direct, cond [][2]string
		for _, line := range strings.Split(string(readme), "\n") {
			t := strings.TrimSpace(line)
			switch {
			case strings.HasPrefix(t, "### OCSF Version"):
				section = "consts"
				continue
			case strings.HasPrefix(t, "### Conditional Mapping"):
				section = "cond"
				continue
			case strings.HasPrefix(t, "### Mapping"):
				section = "direct"
				continue
			case strings.HasPrefix(t, "### Observables"):
				section = ""
				continue
			}
			if section == "consts" {
				if m := bulletRE.FindStringSubmatch(line); m != nil {
					consts = append(consts, [2]string{m[1], m[2]})
				}
				continue
			}
			if section == "" || !strings.HasPrefix(t, "|") {
				continue
			}
			cells := strings.Split(strings.Trim(t, "|"), "|")
			if len(cells) >= 2 && strings.TrimSpace(cells[0]) == "Raw" {
				reversed = true
				continue
			}
			if len(cells) >= 2 && strings.TrimSpace(cells[0]) == "OCSF" {
				reversed = false
				continue
			}
			if len(cells) < 2 {
				continue
			}
			a, b := cellRE.FindStringSubmatch(cells[0]), cellRE.FindStringSubmatch(cells[1])
			if a == nil || b == nil {
				continue
			}
			pair := [2]string{a[1], b[1]}
			if reversed {
				pair = [2]string{b[1], a[1]}
			}
			if section == "direct" {
				direct = append(direct, pair)
			} else {
				cond = append(cond, pair)
			}
		}
		if len(consts) == 0 || len(direct) == 0 {
			fail(fmt.Errorf("%s%s: no constants or mappings parsed", base, d.dir))
		}
		fmt.Fprintf(out, "{version: %q, source: %q, dir: %q,\n", v, d.source, d.dir)
		writePairs(out, "constants", consts)
		writePairs(out, "direct", direct)
		writePairs(out, "conditional", cond)
		out.WriteString("},\n")
	}
}

func writePairs(out *bytes.Buffer, field string, pairs [][2]string) {
	fmt.Fprintf(out, "%s: [][2]string{\n", field)
	for _, p := range pairs {
		fmt.Fprintf(out, "{%q, %q},\n", p[0], p[1])
	}
	out.WriteString("},\n")
}
