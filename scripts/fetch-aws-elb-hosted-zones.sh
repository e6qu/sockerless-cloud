#!/usr/bin/env bash
# Vendor the Elastic Load Balancing canonical hosted zones and regenerate
# simulator-aws/elbv2_hosted_zones_vendored.go from them.
#
# Every load balancer reports the Route 53 hosted zone of its Region and type
# as CanonicalHostedZoneId. AWS lists the zones in the General Reference's
# Elastic Load Balancing endpoints table; the Terraform AWS provider carries
# that table, for its aws_lb_hosted_zone_id data source, in a Go file under a
# license that permits vendoring. The script pins the commit that last touched
# the file, keeps a verbatim gzipped copy beside the other AWS sources, and
# generates the simulator's table from that copy.
set -euo pipefail

REPO="hashicorp/terraform-provider-aws"
UPSTREAM_PATH="internal/service/elbv2/hosted_zone_id_data_source.go"
NAME="elbv2-hosted-zone-ids.go.gz"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/specs/cloud-api/aws/$NAME"
OUT="$ROOT/simulator-aws/elbv2_hosted_zones_vendored.go"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
git clone --quiet --filter=blob:none --no-checkout --single-branch "https://github.com/$REPO" "$work/repo"
SHA="$(git -C "$work/repo" log -1 --format=%H -- "$UPSTREAM_PATH")"
if [ -z "$SHA" ]; then
  echo "no upstream commit found for $UPSTREAM_PATH in $REPO" >&2
  exit 1
fi
echo "Fetching $REPO/$UPSTREAM_PATH @ ${SHA:0:12}"
git -C "$work/repo" show "$SHA:$UPSTREAM_PATH" > "$work/source.go"
gzip -9 -n -c "$work/source.go" > "$DEST"

bash "$ROOT/scripts/spec-sources-row.sh" "$ROOT/specs/cloud-api/aws/SOURCES.md" "aws" \
  "$NAME" "$REPO" "$UPSTREAM_PATH" "MPL-2.0" "$SHA"

python3 - "$work/source.go" "$OUT" <<'PY'
import re, sys

src = open(sys.argv[1]).read()

def region(constant):
    words = re.findall(r'[A-Z][a-z]+|\d+', constant)
    return '-'.join(w.lower() for w in words)

tables = {}
for kind, var in (('application', 'hostedZoneIDPerRegionALBMap'), ('network', 'hostedZoneIDPerRegionNLBMap')):
    m = re.search(r'var ' + var + r' = map\[string\]string\{(.*?)\n\}', src, re.S)
    if not m:
        sys.exit(f'{var} is not in the vendored file')
    rows = re.findall(r'endpoints\.(\w+)RegionID:\s*"([A-Z0-9]+)"', m.group(1))
    if not rows or len(rows) != m.group(1).count('RegionID'):
        sys.exit(f'{var}: parsed {len(rows)} rows of {m.group(1).count("RegionID")}')
    tables[kind] = sorted((region(c), z) for c, z in rows)

with open(sys.argv[2], 'w') as out:
    out.write('// Code generated by scripts/fetch-aws-elb-hosted-zones.sh from\n')
    out.write('// specs/cloud-api/aws/elbv2-hosted-zone-ids.go.gz. DO NOT EDIT.\n\n')
    out.write('package main\n\n')
    out.write('// elbv2HostedZones maps a load balancer type and Region to the Route 53\n')
    out.write('// hosted zone its load balancers report as CanonicalHostedZoneId.\n')
    out.write('var elbv2HostedZones = map[string]map[string]string{\n')
    for kind in ('application', 'network'):
        out.write(f'\t"{kind}": {{\n')
        for r, z in tables[kind]:
            out.write(f'\t\t"{r}": "{z}",\n')
        out.write('\t},\n')
    out.write('}\n')
PY
gofmt -w "$OUT"
echo "Generated $OUT"
