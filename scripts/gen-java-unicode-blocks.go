// gen-java-unicode-blocks writes simulator-aws/cloudwatch_logs_javaregex_blocks_gen.go:
// the Unicode 13.0 blocks, the version Java SE 17's Character.UnicodeBlock
// implements, which java.util.regex.Pattern's \p{InX} and \p{block=X} name.
// The Unicode Consortium publishes each version's Blocks.txt at a fixed URL.
//
// Run from the repository root:
//
//	go run scripts/gen-java-unicode-blocks.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"strings"
)

const source = "https://www.unicode.org/Public/13.0.0/ucd/Blocks.txt"

func main() {
	resp, err := http.Get(source)
	if err != nil {
		fail(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		fail(fmt.Errorf("%s: %s", source, resp.Status))
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by scripts/gen-java-unicode-blocks.go from %s. DO NOT EDIT.\n\n", source)
	out.WriteString("package main\n\nvar cwjBlocks = []struct {\n\tname   string\n\tlo, hi rune\n}{\n")
	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		span, name, ok := strings.Cut(line, ";")
		lo, hi, ok2 := strings.Cut(span, "..")
		if !ok || !ok2 {
			fail(fmt.Errorf("unexpected line %q", line))
		}
		fmt.Fprintf(&out, "\t{%q, 0x%s, 0x%s},\n", strings.TrimSpace(name), lo, hi)
	}
	if err := scanner.Err(); err != nil {
		fail(err)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("simulator-aws/cloudwatch_logs_javaregex_blocks_gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
