//go:build ignore

// gen-aws-service-quotas writes simulator-aws/servicequotas_catalog_gen.go:
// every quota the vendored "endpoints and quotas" pages of the AWS General
// Reference, and the Amazon EC2 instance type quota page, publish with a
// Service Quotas code, for the services the simulator serves. A row's
// Adjustable cell links the quota's Service Quotas console page, which names
// its service code and quota code; a row without that link names no code.
//
// Run from the repository root:
//
//	go run scripts/gen-aws-service-quotas.go [output path]
package main

import (
	"bytes"
	"compress/gzip"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// pages lists the vendored pages in the order a service's name is taken: the
// first page that publishes a service code names its service.
var pages = []string{
	"gr-quotas-acm", "gr-quotas-ak", "gr-quotas-amplify", "gr-quotas-ao", "gr-quotas-apigateway",
	"gr-quotas-as-app", "gr-quotas-as", "gr-quotas-cf-region", "gr-quotas-cloud-map", "gr-quotas-codebuild",
	"gr-quotas-cognito", "gr-quotas-cw-region", "gr-quotas-ev", "gr-quotas-cwl-region", "gr-quotas-ddb",
	"gr-quotas-ebs-service", "gr-quotas-ec2-service", "gr-quotas-ecr", "gr-quotas-ecs-service",
	"gr-quotas-elasticache-service", "gr-quotas-elasticfilesystem", "gr-quotas-elb", "gr-quotas-eventbridgescheduler",
	"gr-quotas-fh", "gr-quotas-glue", "gr-quotas-iam-service", "gr-quotas-kms", "gr-quotas-lambda-service",
	"gr-quotas-pca", "gr-quotas-r53", "gr-quotas-rds-service", "gr-quotas-s3", "gr-quotas-step-functions", "gr-quotas-vpc-service", "gr-quotas-waf",
	"ec2-instance-type-quotas",
}

// served lists the service codes of the services the simulator implements; a
// page's other services (Amazon Cognito identity pools, AWS Private CA
// Connector for SCEP and the like) stay out of the catalog.
var served = map[string]bool{
	"acm": true, "acm-pca": true, "amplify": true, "apigateway": true, "application-autoscaling": true,
	"autoscaling": true, "AWSCloudMap": true, "cloudfront": true, "codebuild": true, "cognito-idp": true,
	"dynamodb": true, "ebs": true, "ec2": true, "ecr": true, "ecs": true, "elasticache": true,
	"elasticfilesystem": true, "elasticloadbalancing": true, "events": true, "fargate": true, "firehose": true,
	"glue": true, "iam": true, "kinesis": true, "kms": true, "lambda": true, "logs": true, "monitoring": true,
	"organizations": true, "rds": true, "route53": true, "s3": true, "scheduler": true,
	"states": true, "vpc": true, "wafv2": true,
}

var (
	codeLink    = regexp.MustCompile(`servicequotas/home/services/([^/]+)/quotas/(L-[0-9A-F]+)`)
	valuePart   = regexp.MustCompile(`^(?:(Each supported Region|Each of the other supported Regions|Each Account|[a-z]{2}(?:-[a-z]+)+-\d+):\s*)?([0-9][0-9,]*(?:\.[0-9]+)?)\s*(.*)$`)
	htmlTag     = regexp.MustCompile(`<[^>]+>`)
	markdownURL = regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`)
)

type quota struct {
	service, serviceName, code, name, description, unit, periodUnit, page string
	value                                                                 float64
	regions                                                               map[string]float64
	global                                                                bool
}

func main() {
	dir := filepath.Join("specs", "cloud-api", "aws")
	names := map[string]string{}
	byCode := map[string]quota{}
	for _, page := range pages {
		text, err := readGzip(filepath.Join(dir, page+".md.gz"))
		if err != nil {
			fail("%v", err)
		}
		for _, q := range parse(page, text) {
			if !served[q.service] {
				continue
			}
			if _, named := names[q.service]; !named {
				names[q.service] = q.serviceName
			}
			key := q.service + "/" + q.code
			if _, seen := byCode[key]; seen {
				continue
			}
			byCode[key] = q
		}
	}
	keys := make([]string, 0, len(byCode))
	for k := range byCode {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var body strings.Builder
	body.WriteString("// Code generated by scripts/gen-aws-service-quotas.go from the vendored quota pages in specs/cloud-api/aws; DO NOT EDIT.\n\npackage main\n\n")
	body.WriteString("var sqCatalog = []sqCatalogQuota{\n")
	for _, k := range keys {
		q := byCode[k]
		fmt.Fprintf(&body, "\t{ServiceCode: %q, ServiceName: %q, QuotaCode: %q, QuotaName: %q, Value: %s, Unit: %q",
			q.service, names[q.service], q.code, q.name, strconv.FormatFloat(q.value, 'f', -1, 64), q.unit)
		if len(q.regions) > 0 {
			regions := make([]string, 0, len(q.regions))
			for r := range q.regions {
				regions = append(regions, r)
			}
			sort.Strings(regions)
			body.WriteString(", RegionValues: map[string]float64{")
			for _, r := range regions {
				fmt.Fprintf(&body, "%q: %s, ", r, strconv.FormatFloat(q.regions[r], 'f', -1, 64))
			}
			body.WriteString("}")
		}
		if q.periodUnit != "" {
			fmt.Fprintf(&body, ", PeriodUnit: %q", q.periodUnit)
		}
		if q.global {
			body.WriteString(", Global: true")
		}
		if q.description != "" {
			fmt.Fprintf(&body, ", Description: %q", q.description)
		}
		fmt.Fprintf(&body, ", Source: %q},\n", q.page+".md.gz")
	}
	body.WriteString("}\n")

	out, err := format.Source([]byte(body.String()))
	if err != nil {
		fail("format: %v", err)
	}
	dest := filepath.Join("simulator-aws", "servicequotas_catalog_gen.go")
	if len(os.Args) > 1 {
		dest = os.Args[1]
	}
	if existing, err := os.ReadFile(dest); err == nil && bytes.Equal(existing, out) {
		return
	}
	if err := os.WriteFile(dest, out, 0o644); err != nil {
		fail("%v", err)
	}
}

// parse reads every quota table of a page: a table whose header starts
// "| Name | Default | Adjustable |". A table takes its service's name from
// the heading above it, or from the page title when that heading is the
// page's own "Service quotas".
func parse(page, text string) []quota {
	lines := strings.Split(text, "\n")
	title := ""
	heading := ""
	var out []quota
	inTable := false
	for _, raw := range lines {
		line := strings.TrimSpace(raw)
		switch {
		case strings.HasPrefix(line, "# ") && title == "":
			title = strings.TrimSuffix(strings.TrimSpace(strings.TrimPrefix(line, "# ")), " endpoints and quotas")
			continue
		case strings.HasPrefix(line, "## ") || strings.HasPrefix(line, "### "):
			heading = strings.TrimSpace(strings.TrimLeft(line, "# "))
			inTable = false
			continue
		case strings.HasPrefix(line, "**") && strings.HasSuffix(line, "**") && len(line) > 4:
			h := strings.Trim(line, "* ")
			if h != "Note" && h != "Important" && h != "Considerations" && h != "Topics" {
				heading = h
			}
			inTable = false
			continue
		}
		if !strings.HasPrefix(line, "|") {
			inTable = false
			continue
		}
		cells := splitRow(line)
		if len(cells) >= 3 && cells[0] == "Name" && cells[1] == "Default" && cells[2] == "Adjustable" {
			inTable = true
			continue
		}
		if !inTable || len(cells) < 3 || strings.HasPrefix(cells[0], "---") {
			continue
		}
		m := codeLink.FindStringSubmatch(cells[2])
		if m == nil {
			continue
		}
		q := quota{service: m[1], code: m[2], name: clean(cells[0]), page: page, unit: "None"}
		q.serviceName = serviceName(title, heading)
		if len(cells) > 3 {
			q.description = clean(cells[3])
		}
		if err := parseDefault(cells[1], &q); err != nil {
			fail("%s: %s: %v", page, q.name, err)
		}
		out = append(out, q)
	}
	return out
}

func serviceName(title, heading string) string {
	h := strings.TrimSuffix(heading, " quotas")
	if h == "" || heading == "Service quotas" || strings.HasSuffix(heading, "instance quotas") ||
		strings.HasSuffix(heading, "Instance quotas") || strings.HasSuffix(heading, "Host quotas") {
		return title
	}
	return h
}

// parseDefault reads a Default cell: one value for every Region, or a value
// per named Region and one for the other Regions, each with an optional unit
// or "per second".
func parseDefault(cell string, q *quota) error {
	for _, part := range strings.Split(cell, "<br />") {
		part = strings.TrimSpace(part)
		m := valuePart.FindStringSubmatch(part)
		if m == nil {
			return fmt.Errorf("default %q", part)
		}
		value, err := strconv.ParseFloat(strings.ReplaceAll(m[2], ",", ""), 64)
		if err != nil {
			return err
		}
		unit := strings.TrimSpace(m[3])
		if rest, ok := strings.CutSuffix(unit, "per second"); ok {
			q.periodUnit = "SECOND"
			unit = strings.TrimSpace(rest)
		}
		if unit != "" {
			q.unit = unit
		}
		switch m[1] {
		case "", "Each supported Region", "Each of the other supported Regions":
			q.value = value
		case "Each Account":
			q.value = value
			q.global = true
		default:
			if q.regions == nil {
				q.regions = map[string]float64{}
			}
			q.regions[m[1]] = value
		}
	}
	return nil
}

func splitRow(line string) []string {
	line = strings.TrimSuffix(strings.TrimPrefix(strings.TrimSpace(line), "|"), "|")
	parts := strings.Split(line, "|")
	for i := range parts {
		parts[i] = strings.TrimSpace(parts[i])
	}
	return parts
}

func clean(s string) string {
	s = markdownURL.ReplaceAllString(s, "$1")
	s = htmlTag.ReplaceAllString(s, " ")
	s = strings.ReplaceAll(s, `\_`, "_")
	s = strings.ReplaceAll(s, `\*`, "*")
	return strings.Join(strings.Fields(s), " ")
}

func readGzip(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	r, err := gzip.NewReader(f)
	if err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	b, err := io.ReadAll(r)
	return string(b), err
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-aws-service-quotas: "+format+"\n", args...)
	os.Exit(1)
}
