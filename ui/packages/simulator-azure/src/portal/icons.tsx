export type AzureIconName = keyof typeof ICONS;

export function AzureIcon({ name, size }: { name: AzureIconName; size?: number | string }) {
  const Icon = ICONS[name];
  return <Icon aria-hidden focusable={false} fontSize={size ?? "1em"} />;
}

/** A service's icon on its colour tile, the way the portal marks each service
 *  in Azure services, All services and resource headers. */
export function ServiceTile({ icon, color, size = 32 }: { icon: AzureIconName; color: string; size?: number }) {
  return (
    <span
      className="az-service-tile"
      aria-hidden
      style={{ width: size, height: size, backgroundColor: color, fontSize: Math.round(size * 0.6) }}
    >
      <AzureIcon name={icon} />
    </span>
  );
}
